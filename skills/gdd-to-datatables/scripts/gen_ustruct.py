"""Genera un header C++ con USTRUCT : FTableRowBase desde un .schema.json.

Uso: python gen_ustruct.py DT_Items.schema.json --out Source/<Modulo>/Data --api <MODULO>_API
Tipos: int->int32, float->float, bool->bool, string->FString, name->FName,
       text->FText, tag->FGameplayTag (requiere el módulo GameplayTags en .Build.cs).
Después de crear o cambiar un USTRUCT: compilar con el editor CERRADO (ue-headless).
"""
import argparse
import json
import os
import sys

CPP = {"int": "int32", "float": "float", "bool": "bool", "string": "FString",
       "name": "FName", "text": "FText", "tag": "FGameplayTag"}
DEFAULT = {"int": " = 0", "float": " = 0.f", "bool": " = false"}


def render(schema, api=""):
    cols = schema["columns"][1:]  # la primera es RowName: no es miembro
    struct = schema["struct"]
    lines = ["// Generated by gen_ustruct.py. Edit the schema, not this file.",
             "#pragma once", "", '#include "CoreMinimal.h"', '#include "Engine/DataTable.h"']
    if any(c["type"] == "tag" for c in cols):
        lines.append('#include "GameplayTagContainer.h"')
    lines += ['#include "%s.generated.h"' % struct[1:], "", "USTRUCT(BlueprintType)",
              "struct %s%s : public FTableRowBase" % ((api + " ") if api else "", struct),
              "{", "\tGENERATED_BODY()", ""]
    for c in cols:
        t, meta = c["type"], ""
        if t in ("int", "float") and "min" in c and "max" in c:
            meta = ', meta=(ClampMin="%s", ClampMax="%s")' % (c["min"], c["max"])
        lines.append("\tUPROPERTY(EditAnywhere, BlueprintReadWrite%s)" % meta)
        lines.append("\t%s %s%s;" % (CPP.get(t, "FString"), c["name"], DEFAULT.get(t, "")))
        lines.append("")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("schema")
    ap.add_argument("--out", default=".")
    ap.add_argument("--api", default="")
    a = ap.parse_args(argv)
    with open(a.schema, encoding="utf-8") as f:
        schema = json.load(f)
    os.makedirs(a.out, exist_ok=True)
    path = os.path.join(a.out, schema["struct"][1:] + ".h")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(schema, a.api))
    print("KIT_INFO escrito", path)
    print("KIT_INFO recordar: compilar con el editor cerrado")
    print("KIT_OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
